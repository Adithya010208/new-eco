/**
 * Predefined 3D Recipe definition for "proj-smart-dustbin"
 * (Smart Dustbin Touchless Lid Opener).
 *
 * TECHNICAL DESIGN & POWER ARCHITECTURE:
 * - Arduino Uno: Microchip ATmega328P 5V logic controller.
 * - HC-SR04 Sonar: 5V DC low-noise ultrasonic distance sensor (~15mA quiescent).
 * - SG90 Micro Servo: 5V DC rotary actuator.
 *
 * POWER SEPARATION RATIONALE:
 * An SG90 micro servo under physical load or momentary stall draws 500mA to 650mA+ peak surge current.
 * The Arduino Uno onboard linear voltage regulator (MC33269D / NCP1117ST50) is only rated for ~150-200mA
 * safe continuous thermal dissipation from a 9V-12V barrel jack, and USB 2.0 ports are capped at 500mA total.
 * Powering a loaded servo directly from the Arduino 5V pin causes inductive voltage sag, microcontroller
 * brownout resets (BOD), and erratic servo jitter.
 *
 * DOCUMENTED POWER ARRANGEMENT:
 * 1. Dedicated External Regulated 5V Supply (1A-2A rating) for the servo motor on the lower breadboard rail.
 * 2. Arduino 5V supply powers only the microcontroller and the low-current HC-SR04 sensor on the upper rail.
 * 3. MANDATORY COMMON GROUND: A common ground bridge connects Arduino GND to the external supply GND bus,
 *    providing the 0V reference needed for Arduino Digital Pin 9 (PWM) to command the servo accurately.
 * 4. STRICT SUPPLY ISOLATION: The Arduino +5V output and External +5V output are kept strictly separate.
 */

